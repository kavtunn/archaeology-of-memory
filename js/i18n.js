  function getLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'be' || saved === 'ru') return saved;
    return 'ru';
  }

  function setLang(lang) {
    if (lang !== 'be' && lang !== 'ru') return;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang === 'be' ? 'be' : 'ru';
    apply();
    window.dispatchEvent(new CustomEvent('memory-lab:lang', { detail: { lang: lang } }));
  }

  function t(key) {
    const pack = UI[getLang()] || UI.ru;
    return pack[key] != null ? pack[key] : UI.ru[key] || key;
  }

  function localizeCase(base) {
    if (!base) return base;
    if (getLang() !== 'be') return base;
    const be = CASES_BE[base.id];
    if (!be) return base;
    const out = Object.assign({}, base, be);
    out.identity = Object.assign({}, base.identity, be.identity || {});
    return out;
  }

  function imageCaption(img) {
    if (!img) return '';
    if (getLang() === 'be' && IMAGE_CAPTIONS_BE[img.id]) return IMAGE_CAPTIONS_BE[img.id];
    return img.caption;
  }

  function apply() {
    const lang = getLang();
    document.documentElement.lang = lang === 'be' ? 'be' : 'ru';

    const nodes = document.querySelectorAll('[data-i18n]');
    for (let i = 0; i < nodes.length; i++) {
      const el = nodes[i];
      const key = el.getAttribute('data-i18n');
      if (!key) continue;
      const val = t(key);
      if (el.tagName === 'TITLE') {
        document.title = val;
      } else if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }

    const ariaNodes = document.querySelectorAll('[data-i18n-aria]');
    for (let j = 0; j < ariaNodes.length; j++) {
      ariaNodes[j].setAttribute('aria-label', t(ariaNodes[j].getAttribute('data-i18n-aria')));
    }

    const titleKey = document.body.getAttribute('data-title-key');
    if (titleKey) document.title = t(titleKey);

    const btns = document.querySelectorAll('.lang-btn');
    for (let k = 0; k < btns.length; k++) {
      const b = btns[k];
      const on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('is-active', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
    }
  }

  function mountChrome() {
    if (document.querySelector('.lang-switch')) return;

    const host = document.querySelector('.site-header__lang, .header-lang');
    if (!host) return;

    const switcher = document.createElement('div');
    switcher.className = 'lang-switch';
    switcher.setAttribute('role', 'group');
    switcher.setAttribute('data-i18n-aria', 'langAria');

    const be = document.createElement('button');
    be.type = 'button';
    be.className = 'lang-btn';
    be.setAttribute('data-lang', 'be');
    be.textContent = 'БЕЛ';

    const ru = document.createElement('button');
    ru.type = 'button';
    ru.className = 'lang-btn';
    ru.setAttribute('data-lang', 'ru');
    ru.textContent = 'РУС';

    switcher.appendChild(be);
    switcher.appendChild(ru);
    host.appendChild(switcher);

    switcher.addEventListener('click', function (e) {
      const btn = e.target.closest('.lang-btn');
      if (!btn) return;
      setLang(btn.getAttribute('data-lang'));
    });
  }

  function boot() {
    mountChrome();
    apply();
  }

  window.MemoryLab = window.MemoryLab || {};
  window.MemoryLab.i18n = {
    t: t,
    getLang: getLang,
    setLang: setLang,
    apply: apply,
    localizeCase: localizeCase,
    imageCaption: imageCaption,
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
